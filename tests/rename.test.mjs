import test from 'node:test'
import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
import {parse} from 'yaml'
import {createRequire} from 'node:module'
import {unseal} from '../src/crypto.mjs'
import {validateSnapshot} from '../src/snapshot.mjs'
import {preview} from '../src/restore.mjs'
import {home} from './helpers.mjs'

test('scoped package exposes new commands and module entries while preserving the old CLI alias',async()=>{
 const meta=JSON.parse(await readFile(new URL('../package.json',import.meta.url),'utf8'))
 const lock=JSON.parse(await readFile(new URL('../package-lock.json',import.meta.url),'utf8'))
 assert.equal(meta.name,'@jeweis/dsh-sync')
 assert.equal(lock.name,meta.name);assert.equal(lock.packages[''].name,meta.name)
 assert.equal(meta.bin['dsh-sync'],meta.bin['dsh-config-vault'])
 const require=createRequire(import.meta.url)
 assert.equal(require.resolve(`${meta.name}/credentials-provider`),new URL('../src/atomic-credentials.mjs',import.meta.url).pathname)
 const patch=await readFile(new URL('../cordis.patch.yml',import.meta.url),'utf8')
 assert.equal(parse(patch)[0].insert[0].id,'dsh-config-vault')
 assert.equal(parse(patch)[0].insert[0].name,meta.name)
 const client=await readFile(new URL('../lib/client.js',import.meta.url),'utf8')
 assert.ok(client.includes('id:"@jeweis/dsh-sync"'))
})

test('DSH Sync authenticates and previews a snapshot generated by the original 0.8.1 package',async t=>{
 // Static synthetic fixture encrypted with crypto.mjs extracted from dsh-config-vault-0.8.1.tgz.
 const snapshot=validateSnapshot(await unseal(await readFile(new URL('./fixtures/legacy-081.vault',import.meta.url)),'test-only-rename-passphrase'))
 assert.equal(snapshot.format,'dsh-config-vault-snapshot')
 const plan=await preview(snapshot,{home:await home(t)})
 assert.equal(plan.blocked,false)
 assert.equal(plan.files[0].path,'profiles/web/package.json')
})
